"""shock_table.h: the shock wave sin(phi) over theta = phi - sigma sin(phi), tabled for the FM-1.

The reference oscillator (not published) solves Kepler's equation with six
warm-started Newton steps a sample, a sine and a cosine in each, in double. A held note's wave is a
fixed function of theta for its sigma, so the FM-1 reads it from a table instead: rows of sigma
0 .. SIG_MAX (denser near the shock), half a period each (the wave is odd about pi: W(2pi - theta) = -W(theta)), int16.
Past sigma = 1 a row starts at the right-hand limit sin(phi_s); the step at the seam is the shock and
the engine puts it back with a polyBLEP of weight sin(phi_s), the BLEP column.

    python make_shock_table.py > shock_table.h
"""
import numpy as np

N = 128            # points over half a period, theta in [0, pi]
SIG_MAX = 3.0
# sigma's rows: tenths, but fortieths from 0.9 to 1.3, where the shock forms and sin(phi_s) climbs as
# sqrt(6 (sigma - 1)): a uniform grid there interpolates the seam's height 0.16 wrong
SIGMAS = sorted(set([round(x, 4) for x in np.arange(0, 0.9, 0.1)] + [round(x, 4) for x in np.arange(0.9, 1.3, 0.025)]
                    + [round(x, 4) for x in np.arange(1.3, SIG_MAX + 1e-9, 0.1)]))
ROWS = len(SIGMAS)


def shock_root(sigma):
    if sigma <= 1.0:
        return 0.0
    lo, hi, phi = 0.0, np.pi, np.pi / 2
    for _ in range(80):
        f = phi - sigma * np.sin(phi)
        if f < 0:
            lo = phi
        else:
            hi = phi
        fp = 1 - sigma * np.cos(phi)
        cand = phi - f / fp if fp > 1e-12 else lo - 1
        phi = cand if lo < cand < hi else 0.5 * (lo + hi)
    return phi


def wave(theta, sigma):
    """sin(phi(theta)) on the branch [phi_s, 2pi - phi_s], theta in [0, 2pi): bisection, so exact everywhere"""
    ps = shock_root(sigma)
    lo = np.full_like(theta, ps)
    hi = np.full_like(theta, 2 * np.pi - ps)
    for _ in range(64):
        mid = 0.5 * (lo + hi)
        f = mid - sigma * np.sin(mid) - theta
        lo = np.where(f < 0, mid, lo)
        hi = np.where(f < 0, hi, mid)
    return np.sin(0.5 * (lo + hi)), ps


def table():
    theta = np.linspace(0, np.pi, N + 1)
    theta[0] = 1e-12                    # the right-hand limit at the seam
    rows, bleps = [], []
    for s in SIGMAS:
        w, ps = wave(theta, s)
        rows.append(np.round(w * 32767).astype(int))
        bleps.append(int(round(np.sin(ps) * 32767)) if s > 1 else 0)
    return rows, bleps


if __name__ == "__main__":
    rows, bleps = table()
    print("/* SPDX-License-Identifier: MIT\n * Copyright (c) 2026 databurn\n"
          " * generated by make_shock_table.py: the shock wave over half a period, by sigma. Do not edit. */")
    print("#ifndef SHOCK_TABLE_H\n#define SHOCK_TABLE_H\n#include <stdint.h>\n")
    print(f"#define SHOCK_N {N}                    /* points over half a period (and one more: pi) */")
    print(f"#define SHOCK_BITS {N.bit_length() - 1}                  /* log2 SHOCK_N */")
    print(f"#define SHOCK_ROWS {ROWS}                 /* sigma 0 .. {SIG_MAX:g}, denser near the shock */")
    print(f"#define SHOCK_SIG_MAX {SIG_MAX:.1f}f\n")
    print("/* each row's sigma, ascending */")
    print("static const float SHOCK_SIG[SHOCK_ROWS] = {" + ", ".join(f"{x:.4f}f" for x in SIGMAS) + "};\n")
    print("static const int16_t SHOCK_TAB[SHOCK_ROWS][SHOCK_N + 1] = {")
    for r in rows:
        vals = [str(v) for v in r]
        lines = [", ".join(vals[i:i + 16]) for i in range(0, len(vals), 16)]
        print("    {" + (",\n     ".join(lines)) + "},")
    print("};\n")
    print("/* the seam's step / 2 (sin(phi_s)), Q15: the polyBLEP's weight per row; 0 below the shock */")
    print("static const int16_t SHOCK_BLEP[SHOCK_ROWS] = {" + ", ".join(str(b) for b in bleps) + "};\n")
    print("#endif")
