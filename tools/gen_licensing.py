"""gen_licensing.py [--check]: LICENSING.md's per-file table, from the SPDX headers of the tracked source files.

Every source file under firmware/, tools/, tests/ and web/ (and build.sh) must carry an SPDX-License-Identifier in
its first lines. The table lists each file whose licence is not GPL-3.0-only, with its licence and copyright line as
the header states them, and counts the GPL-3.0-only ones; it replaces the text between the two auto:spdx markers in
LICENSING.md. --check writes nothing and fails if a file has no SPDX line or the table in LICENSING.md is stale."""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXT = (".c", ".h", ".S", ".ld", ".py", ".sh", ".js", ".mjs", ".html")
DIRS = ("firmware/", "tools/", "tests/", "web/")
SKIP = ("firmware/src/banks/",)                         # generated data, listed in LICENSING.md on its own
BEGIN, END = "<!-- auto:spdx -->", "<!-- /auto:spdx -->"


def files():
    r = subprocess.run(["git", "-C", ROOT, "ls-files"], capture_output=True, text=True)
    if r.returncode == 0:
        names = r.stdout.split("\n")
    else:                                               # (a source archive, not a checkout: the tree as it is)
        names = ["build.sh"] + [os.path.relpath(os.path.join(d, n), ROOT).replace(os.sep, "/")
                                for top in DIRS for d, _, fs in os.walk(os.path.join(ROOT, top)) for n in fs]
    for f in names:
        if (f == "build.sh" or (f.startswith(DIRS) and f.endswith(EXT))) and not f.startswith(SKIP):
            yield f


def header(path):
    with open(os.path.join(ROOT, path), encoding="utf-8", errors="replace") as fh:
        head = "".join(fh.readline() for _ in range(6))
    m = re.search(r"SPDX-License-Identifier:\s*([A-Za-z0-9.+\- ]+?)\s*(?:\*/|-->|\n|$)", head)
    c = re.search(r"Copyright\s+(?:\(C\)\s*|\(c\)\s*)?(.+?)\s*(?:\*/|-->|\n|$)", head)
    return (m.group(1).strip() if m else None), (c.group(1).strip() if c else "")


def table():
    rows, missing, gpl = [], [], 0
    for f in sorted(files()):
        lic, who = header(f)
        if not lic:
            missing.append(f)
        elif lic == "GPL-3.0-only":
            gpl += 1
        else:
            rows.append((f, lic, who or "(no copyright line)"))
    lines = [BEGIN, "",
             f"Generated by `tools/gen_licensing.py` from the files' SPDX headers: {gpl} source files are "
             f"GPL-3.0-only, and these {len(rows)} carry another licence.", "",
             "| File | Licence | Copyright |", "| --- | --- | --- |"]
    lines += [f"| `{f}` | {lic} | {who} |" for f, lic, who in rows]
    lines += ["", END]
    return "\n".join(lines), missing


def main():
    check = "--check" in sys.argv
    path = os.path.join(ROOT, "LICENSING.md")
    doc = open(path, encoding="utf-8").read()
    if BEGIN not in doc or END not in doc:
        sys.exit("gen_licensing: LICENSING.md has no auto:spdx markers")
    block, missing = table()
    new = doc[:doc.index(BEGIN)] + block + doc[doc.index(END) + len(END):]
    for f in missing:
        print(f"gen_licensing: {f}: no SPDX-License-Identifier", file=sys.stderr)
    if check:
        if new != doc:
            print("gen_licensing: LICENSING.md's table is stale (run tools/gen_licensing.py)", file=sys.stderr)
        sys.exit(1 if missing or new != doc else 0)
    if new != doc:
        open(path, "w", encoding="utf-8").write(new)
    print(f"gen_licensing: {block.count(chr(10) + '| `')} files listed" + (f", {len(missing)} without SPDX" if missing else ""))
    sys.exit(1 if missing else 0)


if __name__ == "__main__":
    main()
